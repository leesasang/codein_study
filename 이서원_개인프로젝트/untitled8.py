import requests
import pandas as pd
import numpy as np
from io import StringIO

# =========================
# 1. 행성 코드: JPL Horizons COMMAND ID
# =========================

PLANETS = {
    "수성": {"id": "199", "period": 87.969},
    "금성": {"id": "299", "period": 224.701},
    "지구": {"id": "399", "period": 365.256},
    "화성": {"id": "499", "period": 686.980},
    "목성": {"id": "599", "period": 4332.589},
    "토성": {"id": "699", "period": 10759.22},
    "천왕성": {"id": "799", "period": 30685.4},
    "해왕성": {"id": "899", "period": 60189.0},
}

API_URL = "https://ssd.jpl.nasa.gov/api/horizons.api"


# =========================
# 2. 회합주기 계산
# =========================

def synodic_period(body1, body2):
    """
    두 천체의 공전주기를 이용해 회합주기 계산
    S = 1 / |1/P1 - 1/P2|
    """
    p1 = PLANETS[body1]["period"]
    p2 = PLANETS[body2]["period"]
    return 1 / abs(1 / p1 - 1 / p2)


# =========================
# 3. NASA/JPL Horizons API에서 적경 가져오기
# =========================

def fetch_ra_from_horizons(planet_name, start_time, stop_time, step_size="1 d"):
    """
    행성의 적경 RA 값을 가져오는 함수
    CENTER='500@10'은 태양 중심 기준
    ANG_FORMAT='DEG'는 각도를 도 단위로 받기 위한 설정
    """
    command_id = PLANETS[planet_name]["id"]

    params = {
        "format": "text",
        "COMMAND": command_id,
        "CENTER": "500@10",
        "EPHEM_TYPE": "OBSERVER",
        "MAKE_EPHEM": "YES",
        "OBJ_DATA": "NO",
        "QUANTITIES": "1",
        "CSV_FORMAT": "YES",
        "ANG_FORMAT": "DEG",
        "REF_SYSTEM": "ICRF",
        "START_TIME": start_time,
        "STOP_TIME": stop_time,
        "STEP_SIZE": step_size,
        "TIME_DIGITS": "SECONDS",
    }

    response = requests.get(API_URL, params=params, timeout=30)
    response.raise_for_status()
    text = response.text

    if "$$SOE" not in text or "$$EOE" not in text:
        raise ValueError(f"{planet_name} 데이터를 읽지 못했습니다.\n{text[:1000]}")

    table_text = text.split("$$SOE")[1].split("$$EOE")[0].strip()

    raw = pd.read_csv(StringIO(table_text), header=None)
    raw.columns = [f"col{i}" for i in range(raw.shape[1])]

    raw["datetime"] = pd.to_datetime(
        raw["col0"].astype(str).str.strip(),
        errors="coerce"
    )

    # 날짜 다음에 나오는 0~360 범위의 숫자열을 RA 열로 추정
    ra_col = None
    for col in raw.columns[1:]:
        nums = pd.to_numeric(raw[col], errors="coerce")
        if nums.notna().sum() > 0:
            ratio = nums.dropna().between(0, 360).mean()
            if ratio > 0.8:
                ra_col = col
                break

    if ra_col is None:
        raise ValueError(f"{planet_name}의 적경 RA 열을 찾지 못했습니다.")

    result = pd.DataFrame({
        "datetime": raw["datetime"],
        planet_name: pd.to_numeric(raw[ra_col], errors="coerce")
    }).dropna()

    return result


