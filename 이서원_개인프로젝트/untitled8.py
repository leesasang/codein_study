# 5. 가장 가까운 정렬 시각 찾기
# =========================

def find_closest_alignment(input_planets, start="2026-01-01", years=80):
    """
    입력한 행성들의 적경이 가장 비슷해지는 시각을 찾는다.

    1차 탐색: 일 단위
    2차 탐색: 가장 좋은 날짜 주변을 시간 단위로 다시 탐색
    """
    input_planets = [p.strip() for p in input_planets]

    for p in input_planets:
        if p not in PLANETS:
            raise ValueError(f"지원하지 않는 천체입니다: {p}")

    start_dt = pd.to_datetime(start)
    stop_dt = start_dt + pd.DateOffset(years=years)

    start_str = start_dt.strftime("%Y-%b-%d")
    stop_str = stop_dt.strftime("%Y-%b-%d")

    print("1차 탐색: 일 단위 데이터 수집 중...")

    dfs = []

    for planet in input_planets:
        df = fetch_ra_from_horizons(
            planet,
            start_time=start_str,
            stop_time=stop_str,
            step_size="1 d"
        )
        dfs.append(df)

    merged = dfs[0]

    for df in dfs[1:]:
        merged = pd.merge(merged, df, on="datetime", how="inner")

    spreads = []
    orders = []
    ordered_ras = []

    for _, row in merged.iterrows():
        ra_values = [row[p] for p in input_planets]
        spread, order, order_ra = circular_spread_and_order(
            ra_values,
            input_planets
        )

        spreads.append(spread)
        orders.append(order)
        ordered_ras.append(order_ra)

    merged["spread_deg"] = spreads
    merged["order"] = orders
    merged["ordered_ra"] = ordered_ras

    best_day = merged.loc[merged["spread_deg"].idxmin()]
    best_time = best_day["datetime"]

    print("2차 탐색: 가장 좋은 날짜 주변을 시간 단위로 재탐색 중...")

    refine_start = best_time - pd.Timedelta(days=3)
    refine_stop = best_time + pd.Timedelta(days=3)

    dfs = []

    for planet in input_planets:
        df = fetch_ra_from_horizons(
            planet,
            start_time=refine_start.strftime("%Y-%b-%d %H:%M:%S"),
            stop_time=refine_stop.strftime("%Y-%b-%d %H:%M:%S"),
            step_size="1 h"
        )
        dfs.append(df)

    refined = dfs[0]

    for df in dfs[1:]:
        refined = pd.merge(refined, df, on="datetime", how="inner")

    spreads = []
    orders = []
    ordered_ras = []

    for _, row in refined.iterrows():
        ra_values = [row[p] for p in input_planets]
        spread, order, order_ra = circular_spread_and_order(
            ra_values,
            input_planets
        )

        spreads.append(spread)
        orders.append(order)
        ordered_ras.append(order_ra)

    refined["spread_deg"] = spreads
    refined["order"] = orders
    refined["ordered_ra"] = ordered_ras

    best = refined.loc[refined["spread_deg"].idxmin()]

    result = {
        "입력": input_planets,
        "행성_순서": best["order"],
        "가장_가까운_일시_UTC": best["datetime"],
        "적경_도": dict(zip(best["order"], np.round(best["ordered_ra"], 4))),
        "모임_각도폭_도": round(best["spread_deg"], 4)
    }

    return result


