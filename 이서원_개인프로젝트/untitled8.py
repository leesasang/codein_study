# 4. 적경 순서와 모임 정도 계산
# =========================

def circular_spread_and_order(ra_values, names):
    """
    적경은 0~360도 원형 값이다.
    따라서 단순히 max - min을 쓰면 안 된다.

    예:
    359도와 1도는 실제로 358도 차이가 아니라 2도 차이다.
    """
    ra_values = np.array(ra_values, dtype=float) % 360
    names = np.array(names)

    order = np.argsort(ra_values)
    sorted_ra = ra_values[order]
    sorted_names = names[order]

    gaps = np.diff(sorted_ra)
    wrap_gap = 360 - sorted_ra[-1] + sorted_ra[0]
    gaps = np.append(gaps, wrap_gap)

    max_gap_index = np.argmax(gaps)
    spread = 360 - gaps[max_gap_index]

    start = (max_gap_index + 1) % len(sorted_ra)

    ordered_names = list(np.roll(sorted_names, -start))
    ordered_ra = list(np.roll(sorted_ra, -start))

    return spread, ordered_names, ordered_ra


